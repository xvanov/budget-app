"""AES-256-GCM secret encryption, including cross-app compatibility.

The whole point of app/services/crypto.py is that it speaks the same wire
format as rental-management/src/lib/crypto/secrets.ts, so one ENCRYPTION_KEY
serves both apps. NODE_FIXTURE below was produced by running that TS module's
algorithm under node (createCipheriv aes-256-gcm, 12-byte iv, separate auth
tag) — decrypting it here is what actually proves compatibility, rather than a
Python round-trip that would pass even if the format had drifted.

The key is a throwaway test value, not the real ENCRYPTION_KEY.
"""
import base64

import pytest

from app.services.crypto import (
    EncryptionError,
    decrypt_secret,
    encrypt_secret,
    is_encryption_configured,
)

TEST_KEY = "YnVkZ2V0LWFwcC10ZXN0LWtleS1ub3QtYS1zZWNyZXQ="  # b"budget-app-test-key-not-a-secret"

# Generated by node using secrets.ts's exact algorithm.
NODE_FIXTURE = {
    "plaintext": "access-sandbox-4f2c1e7a-cross-app-fixture",
    "payload": "v1:R6miyr4mo4Xt2SxU:DMmliQZ+IB488l83eY3tnA==:x3PndqPpDSxVK7ly6HMciXBPKhWZRrPmlyEpWQnm5i8nxbxuR8V2Lho=",
}


@pytest.fixture(autouse=True)
def _key(monkeypatch):
    monkeypatch.setenv("ENCRYPTION_KEY", TEST_KEY)


def test_decrypts_ciphertext_produced_by_the_node_implementation():
    """Cross-app compatibility — the reason this module is a port, not a rewrite."""
    assert decrypt_secret(NODE_FIXTURE["payload"]) == NODE_FIXTURE["plaintext"]


def test_round_trip():
    token = "access-production-8b1d0c33-9f7e-4a21-b6d5-0e2c7a914f88"
    assert decrypt_secret(encrypt_secret(token)) == token


def test_wire_format_matches_the_ts_contract():
    payload = encrypt_secret("hello")
    version, iv_b64, tag_b64, ct_b64 = payload.split(":")
    assert version == "v1"
    assert len(base64.b64decode(iv_b64)) == 12, "GCM standard nonce length"
    assert len(base64.b64decode(tag_b64)) == 16, "auth tag must be its own field, as in node"
    assert base64.b64decode(ct_b64)  # non-empty ciphertext


def test_nonce_is_fresh_per_call():
    """Reusing a GCM nonce under one key is catastrophic — verify we never do."""
    payloads = {encrypt_secret("same-plaintext") for _ in range(25)}
    assert len(payloads) == 25
    ivs = {p.split(":")[1] for p in payloads}
    assert len(ivs) == 25


def test_tampered_ciphertext_is_rejected():
    payload = encrypt_secret("sensitive")
    version, iv_b64, tag_b64, ct_b64 = payload.split(":")
    raw = bytearray(base64.b64decode(ct_b64))
    raw[0] ^= 0x01
    tampered = ":".join([version, iv_b64, tag_b64, base64.b64encode(bytes(raw)).decode()])
    with pytest.raises(EncryptionError, match="authentication failed"):
        decrypt_secret(tampered)


def test_wrong_key_is_rejected(monkeypatch):
    payload = encrypt_secret("sensitive")
    other = base64.b64encode(b"a-different-32-byte-test-key-!!!").decode()
    monkeypatch.setenv("ENCRYPTION_KEY", other)
    with pytest.raises(EncryptionError, match="authentication failed"):
        decrypt_secret(payload)


@pytest.mark.parametrize(
    "payload",
    [
        "",
        "not-a-payload",
        "v2:aaaa:bbbb:cccc",  # unknown version
        "v1:aaaa:bbbb",  # too few fields
        "v1:!!!:bbbb:cccc",  # not base64
    ],
)
def test_malformed_payloads_raise(payload):
    with pytest.raises(EncryptionError):
        decrypt_secret(payload)


def test_missing_key_raises_with_actionable_message(monkeypatch):
    monkeypatch.delenv("ENCRYPTION_KEY", raising=False)
    assert is_encryption_configured() is False
    with pytest.raises(EncryptionError, match="openssl rand -base64 32"):
        encrypt_secret("x")


@pytest.mark.parametrize(
    "bad_key",
    [
        base64.b64encode(b"too-short").decode(),
        "not base64 at all !!!",
    ],
)
def test_wrong_sized_or_invalid_key_raises(monkeypatch, bad_key):
    monkeypatch.setenv("ENCRYPTION_KEY", bad_key)
    assert is_encryption_configured() is False
    with pytest.raises(EncryptionError):
        encrypt_secret("x")


def test_is_encryption_configured_true_with_valid_key():
    assert is_encryption_configured() is True
